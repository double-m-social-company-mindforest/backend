def get_keyword_ids_from_genealogy(character_name: str) -> dict:
    """캐릭터 족보에서 키워드 ID 조합을 반환"""
    if character_name not in CHARACTER_GENEALOGY:
        return None
    
    genealogy = CHARACTER_GENEALOGY[character_name]
    
    return {
        "1": [KEYWORD_NAME_TO_ID[keyword] for keyword in genealogy["마음"]],  # 마음 카테고리
        "2": [KEYWORD_NAME_TO_ID[keyword] for keyword in genealogy["일상"]],  # 일상 카테고리  
        "3": [KEYWORD_NAME_TO_ID[keyword] for keyword in genealogy["여유"]]   # 여유 카테고리
    }

def get_all_genealogy_test_cases():
    """모든 캐릭터의 테스트 케이스 생성"""
    test_cases = []
    
    for character_name, genealogy in CHARACTER_GENEALOGY.items():
        keyword_ids = get_keyword_ids_from_genealogy(character_name)
        if keyword_ids:
            test_cases.append({
                "character_name": character_name,
                "expected_final_type_id": genealogy["final_type_id"],
                "keyword_ids": keyword_ids
            })
    
    return test_cases